from playwright.async_api import async_playwright
B = "http://127.0.0.1:8767/"
S = __import__("os").path.dirname(__import__("os").path.abspath(__file__)) + "/"
async def main():
    async with async_playwright() as p:
        br = await p.chromium.launch()
        ctx = await br.new_context(geolocation={"latitude": 32.191, "longitude": 73.031}, permissions=["geolocation"], viewport={"width": 400, "height": 860})
        cu = await ctx.new_page(); errs = []
        cu.on("pageerror", lambda e: errs.append("cust " + str(e)))
        await cu.goto(B + "customer-app/index.html")
        await cu.wait_for_function("localStorage.getItem('kmd_seeded_kyc') === '1'", timeout=20000)
        await cu.evaluate("""() => { const s = JSON.parse(localStorage.getItem('kmd_settings')); s[0].openFrom = 0; s[0].openTo = 24; localStorage.setItem('kmd_settings', JSON.stringify(s)); }""")
        await cu.reload(); await cu.wait_for_selector("#app:not([hidden])", timeout=10000)
        await cu.click("[data-cat=pharmacy]")
        await cu.fill("#items", "Medicines as per photo"); await cu.fill("#estimate", "500")
        await cu.locator("#photoIn").set_input_files(S + "receipt.jpg"); await cu.wait_for_timeout(600)
        await cu.click("#send"); await cu.wait_for_selector("#v-track:not([hidden])", timeout=8000)
        no = (await cu.inner_text("#trNo")).strip(); code = (await cu.inner_text("#trCodeVal")).strip()
        o = await cu.evaluate(f"JSON.parse(localStorage.getItem('kmd_orders')).find(o => o.no === '{no}')")
        print("1 order", no, "photoId:", bool(o.get("photoId")), "| inline photo in order:", "listPhoto" in o and bool(o.get("listPhoto")), "| order JSON size:", len(str(o)))
        print("  media docs:", await cu.evaluate("JSON.parse(localStorage.getItem('kmd_media') || '[]').map(m => m.kind + ':' + m.data.length)"))
        print("  customer sees own photo:", await cu.eval_on_selector("#trMeta img", "e => (e.getAttribute('src') || '').slice(0, 22)"))
        rd = await ctx.new_page(); rd.on("pageerror", lambda e: errs.append("rider " + str(e)))
        await rd.goto(B + "rider-app/index.html"); await rd.fill("#phone", "03111234567"); await rd.fill("#pin", "7390"); await rd.click("#loginForm button[type=submit]")
        await rd.wait_for_selector("#app:not([hidden])")
        card = rd.locator("article", has_text=no); await card.wait_for(timeout=8000); await rd.wait_for_timeout(1500)
        print("2 rider sees customer photo:", await card.locator("img.billimg").evaluate("e => (e.getAttribute('src') || '').slice(0, 22)"))
        # Bilal already has D6 active; max 2 -> can accept one more
        await card.locator("[data-a=accept]").click(); await rd.wait_for_timeout(500)
        art = rd.locator("article", has_text=no)
        await art.locator("[data-a=confirm]").click(); await art.locator("[data-bill]").wait_for()
        await art.locator("[data-bill]").fill("480"); await rd.locator("body").click(position={"x": 5, "y": 5})
        await art.locator("input[type=file]").set_input_files(S + "receipt.jpg"); await rd.wait_for_timeout(800)
        await art.locator("[data-a=pick]").click(); await art.locator("[data-a=arrived]").wait_for(timeout=6000)
        o = await cu.evaluate(f"JSON.parse(localStorage.getItem('kmd_orders')).find(o => o.no === '{no}')")
        print("3 receiptId:", bool(o.get("receiptId")), "| inline receipt:", bool(o.get("receipt")), "| pickedLoc:", o.get("pickedLoc"))
        await cu.wait_for_function("document.querySelector('#rcptImg') && (document.querySelector('#rcptImg').getAttribute('src') || '').startsWith('data:image')", timeout=8000)
        print("4 customer sees bill photo: yes")
        ad = await ctx.new_page(); ad.on("pageerror", lambda e: errs.append("admin " + str(e)))
        await ad.set_viewport_size({"width": 1300, "height": 860})
        await ad.goto(B + "admin-web/index.html"); await ad.fill("#pin", "786512"); await ad.click("#loginForm button[type=submit]")
        await ad.wait_for_selector("#shell:not([hidden])"); await ad.click("#nav button[data-v=orders]")
        await ad.locator("#oTbl tbody tr", has_text=no).click(); await ad.wait_for_selector("#drawer")
        await ad.wait_for_timeout(800)
        imgs = await ad.eval_on_selector_all("#drawer img.receipt", "els => els.map(e => (e.getAttribute('src') || 'none').slice(0, 15))")
        print("5 admin drawer images:", imgs, "| no-bill-photo flag:", "No bill photo" in await ad.inner_text("#drawer"))
        print("  assign list:", re.sub(r"\s+", " ", await ad.inner_text("#drawer")).count("km away"))
        print("errors:", errs or "none")
        await br.close()
asyncio.run(main())
